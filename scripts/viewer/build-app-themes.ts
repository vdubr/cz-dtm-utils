/**
 * Generátor barevných schémat nástrojů DTM Prohlížeče (Material 3).
 *
 * Každý nástroj (JVF / UDM / JŽM) má vlastní barevné schéma rozhraní ze
 * základní barvy (seed), pro světlý i tmavý motiv: UDM zelené, JŽM
 * oranžové jako Správa železnic (#ff5200 z loga SŽ). Primární paleta má plnou sytost základní barvy
 * (TonalSpot by ji zašedil), role a tóny jsou podle M3 (TonalSpot, 2021). JVF zůstává u ručně
 * laděného schématu v `jvf_viewer/src/m3.css` (`:root`), UDM a JŽM se
 * generují sem jako přepis proměnných `--md-sys-color-*` pod
 * `:root[data-app='…']`. Barvy chyb / varování / úspěchu a barvy dat v mapě
 * se nemění.
 *
 * Spuštění z rootu repa:
 *   npx tsx scripts/viewer/build-app-themes.ts
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import {
  DynamicScheme,
  Hct,
  MaterialDynamicColors,
  TonalPalette,
  Variant,
  argbFromHex,
  hexFromArgb,
} from '@material/material-color-utilities';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = resolve(ROOT, 'jvf_viewer/src/app-themes.css');

interface AppTheme {
  id: string;
  name: string;
  /** Základní (primární) barva = barva odznaku nástroje. */
  seed: string;
  /** Kontrastní barva (sekundární, terciární a nádech povrchů); jinak odvozená ze seed. */
  contrast?: string;
}

/** Nástroje s vlastním schématem (JVF = výchozí v m3.css). */
const APPS: AppTheme[] = [
  { id: 'udm', name: 'UDM — Univerzální datový model ČKZ (zelená)', seed: '#2e7d32' },
  { id: 'jzm', name: 'JŽM — Jednotná železniční mapa (oranžová SŽ)', seed: '#ff5200' },
];

/** Schéma M3: primární paleta s plnou sytostí základu, ostatní podle TonalSpot / kontrastní barvy. */
function schemeFor(app: AppTheme, isDark: boolean): DynamicScheme {
  const seed = Hct.fromInt(argbFromHex(app.seed));
  const contrast = app.contrast ? Hct.fromInt(argbFromHex(app.contrast)) : null;
  return new DynamicScheme({
    sourceColorHct: seed,
    variant: Variant.TONAL_SPOT,
    contrastLevel: 0,
    isDark,
    specVersion: '2021',
    primaryPalette: TonalPalette.fromHueAndChroma(seed.hue, Math.max(seed.chroma, 48)),
    secondaryPalette: contrast
      ? TonalPalette.fromHueAndChroma(contrast.hue, Math.max(contrast.chroma, 36))
      : TonalPalette.fromHueAndChroma(seed.hue, 16),
    tertiaryPalette: contrast
      ? TonalPalette.fromHueAndChroma(contrast.hue, 24)
      : TonalPalette.fromHueAndChroma((seed.hue + 60) % 360, 24),
    neutralPalette: TonalPalette.fromHueAndChroma((contrast ?? seed).hue, 4),
    neutralVariantPalette: TonalPalette.fromHueAndChroma((contrast ?? seed).hue, 8),
  });
}

/** Proměnné M3 přepisované schématem nástroje → role dynamické barvy. */
const TOKENS: [string, keyof typeof MaterialDynamicColors][] = [
  ['primary', 'primary'],
  ['on-primary', 'onPrimary'],
  ['primary-container', 'primaryContainer'],
  ['on-primary-container', 'onPrimaryContainer'],
  ['secondary', 'secondary'],
  ['on-secondary', 'onSecondary'],
  ['secondary-container', 'secondaryContainer'],
  ['on-secondary-container', 'onSecondaryContainer'],
  ['tertiary', 'tertiary'],
  ['tertiary-container', 'tertiaryContainer'],
  ['on-tertiary-container', 'onTertiaryContainer'],
  ['surface', 'surface'],
  ['surface-dim', 'surfaceDim'],
  ['surface-bright', 'surfaceBright'],
  ['surface-container-lowest', 'surfaceContainerLowest'],
  ['surface-container-low', 'surfaceContainerLow'],
  ['surface-container', 'surfaceContainer'],
  ['surface-container-high', 'surfaceContainerHigh'],
  ['surface-container-highest', 'surfaceContainerHighest'],
  ['on-surface', 'onSurface'],
  ['on-surface-variant', 'onSurfaceVariant'],
  ['outline', 'outline'],
  ['outline-variant', 'outlineVariant'],
  ['inverse-surface', 'inverseSurface'],
  ['inverse-on-surface', 'inverseOnSurface'],
  ['inverse-primary', 'inversePrimary'],
];

function block(selector: string, scheme: DynamicScheme, dark: boolean): string {
  const lines = TOKENS.map(([name, role]) => {
    const color = (MaterialDynamicColors[role] as { getArgb(s: DynamicScheme): number }).getArgb(scheme);
    return `  --md-sys-color-${name}: ${hexFromArgb(color)};`;
  });
  return `${selector} {\n${dark ? '  color-scheme: dark;\n' : ''}${lines.join('\n')}\n}\n`;
}

let css = `/* Auto-generated by scripts/viewer/build-app-themes.ts — DO NOT EDIT
 *
 * Barevná schémata nástrojů DTM Prohlížeče (Material 3, role TonalSpot, primární paleta s plnou sytostí, ze
 * základní barvy nástroje). JVF = výchozí schéma v m3.css. Atribut
 * \`data-app\` na <html> nastavuje ui/appModeSwitch.ts podle režimu.
 */
`;
for (const app of APPS) {
  css += `\n/* ${app.name} — základ ${app.seed}${app.contrast ? `, kontrast ${app.contrast}` : ''} */\n`;
  css += block(`:root[data-app='${app.id}']`, schemeFor(app, false), false);
  css += block(`:root[data-app='${app.id}'][data-theme='dark']`, schemeFor(app, true), true);
}
writeFileSync(OUT, css, 'utf8');
console.log(`${APPS.length} schémata → ${OUT}`);
