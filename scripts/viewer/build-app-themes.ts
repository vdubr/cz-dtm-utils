/**
 * Generátor barevných schémat nástrojů DTM Prohlížeče (Material 3).
 *
 * Každý nástroj (JVF / UDM / JŽM) má vlastní barevné schéma rozhraní ze
 * základní barvy (seed), pro světlý i tmavý motiv. JVF zůstává u ručně
 * laděného schématu v `jvf_viewer/src/m3.css` (`:root`), UDM a JŽM se
 * generují sem jako přepis proměnných `--md-sys-color-*` pod
 * `:root[data-app='…']`. Barvy chyb / varování / úspěchu a barvy dat v mapě
 * se nemění.
 *
 * Spuštění z rootu repa:
 *   npx tsx scripts/viewer/build-app-themes.ts
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import {
  Hct,
  MaterialDynamicColors,
  SchemeTonalSpot,
  argbFromHex,
  hexFromArgb,
  type DynamicScheme,
} from '@material/material-color-utilities';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = resolve(ROOT, 'jvf_viewer/src/app-themes.css');

/** Nástroje s vlastním schématem — základní barva = barva odznaku nástroje. */
const APPS: { id: string; name: string; seed: string }[] = [
  { id: 'udm', name: 'UDM — Univerzální datový model ČKZ', seed: '#00796b' },
  { id: 'jzm', name: 'JŽM — Jednotná železniční mapa (SŽ)', seed: '#b3400b' },
];

/** Proměnné M3 přepisované schématem nástroje → role dynamické barvy. */
const TOKENS: [string, keyof typeof MaterialDynamicColors][] = [
  ['primary', 'primary'],
  ['on-primary', 'onPrimary'],
  ['primary-container', 'primaryContainer'],
  ['on-primary-container', 'onPrimaryContainer'],
  ['secondary', 'secondary'],
  ['on-secondary', 'onSecondary'],
  ['secondary-container', 'secondaryContainer'],
  ['on-secondary-container', 'onSecondaryContainer'],
  ['tertiary', 'tertiary'],
  ['tertiary-container', 'tertiaryContainer'],
  ['on-tertiary-container', 'onTertiaryContainer'],
  ['surface', 'surface'],
  ['surface-dim', 'surfaceDim'],
  ['surface-bright', 'surfaceBright'],
  ['surface-container-lowest', 'surfaceContainerLowest'],
  ['surface-container-low', 'surfaceContainerLow'],
  ['surface-container', 'surfaceContainer'],
  ['surface-container-high', 'surfaceContainerHigh'],
  ['surface-container-highest', 'surfaceContainerHighest'],
  ['on-surface', 'onSurface'],
  ['on-surface-variant', 'onSurfaceVariant'],
  ['outline', 'outline'],
  ['outline-variant', 'outlineVariant'],
  ['inverse-surface', 'inverseSurface'],
  ['inverse-on-surface', 'inverseOnSurface'],
  ['inverse-primary', 'inversePrimary'],
];

function block(selector: string, scheme: DynamicScheme, dark: boolean): string {
  const lines = TOKENS.map(([name, role]) => {
    const color = (MaterialDynamicColors[role] as { getArgb(s: DynamicScheme): number }).getArgb(scheme);
    return `  --md-sys-color-${name}: ${hexFromArgb(color)};`;
  });
  return `${selector} {\n${dark ? '  color-scheme: dark;\n' : ''}${lines.join('\n')}\n}\n`;
}

let css = `/* Auto-generated by scripts/viewer/build-app-themes.ts — DO NOT EDIT
 *
 * Barevná schémata nástrojů DTM Prohlížeče (Material 3, SchemeTonalSpot — stejný charakter jako JVF —, ze
 * základní barvy nástroje). JVF = výchozí schéma v m3.css. Atribut
 * \`data-app\` na <html> nastavuje ui/appModeSwitch.ts podle režimu.
 */
`;
for (const app of APPS) {
  const hct = Hct.fromInt(argbFromHex(app.seed));
  css += `\n/* ${app.name} — základ ${app.seed} */\n`;
  css += block(`:root[data-app='${app.id}']`, new SchemeTonalSpot(hct, false, 0, '2021'), false);
  css += block(`:root[data-app='${app.id}'][data-theme='dark']`, new SchemeTonalSpot(hct, true, 0, '2021'), true);
}
writeFileSync(OUT, css, 'utf8');
console.log(`${APPS.length} schémata → ${OUT}`);
