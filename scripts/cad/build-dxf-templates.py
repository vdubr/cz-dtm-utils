#!/usr/bin/env python3
"""
Generátor šablon prázdného výkresu DXF pro export do CAD (balíček jvf-cad).

AutoCAD je u DXF R2000+ přísný na strukturu (handly, vlastníci, slovníky,
objekty LAYOUT). Kostru výkresu proto vyrábí knihovna ezdxf, jejíž výstup
AutoCAD spolehlivě otevírá; jvf-cad do šablony jen doplňuje hladiny, typy
čar, bloky a entity (viz jvf_cad/src/dxf/template.ts).

Šablony obsahují navíc:
  - jednotky metry ($INSUNITS = 6, $MEASUREMENT = 1),
  - APPID „UDM" (registrace aplikace pro XDATA s atributy objektů),
  - textový styl „UDM" s fontem Arial Narrow (doporučení UDM, kap. 15.2),
  - R2000: kódová stránka ANSI_1250 (čeština; pro starší CAD).

Potřebuje ezdxf (jen pro vývojáře, ne runtime):
    python3 -m venv .venv && .venv/bin/pip install ezdxf
    .venv/bin/python scripts/cad/build-dxf-templates.py
"""
import json
from pathlib import Path

import ezdxf

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'jvf_cad/src/generated/templates.ts'


def template(version: str) -> str:
    doc = ezdxf.new(version, setup=False)
    doc.header['$INSUNITS'] = 6
    doc.header['$MEASUREMENT'] = 1
    if version == 'R2000':
        # ezdxf zapisuje $DWGCODEPAGE podle kódování dokumentu.
        doc.encoding = 'cp1250'
    doc.appids.add('UDM')
    doc.styles.add('UDM', font='arialn.ttf')
    stream = __import__('io').StringIO()
    doc.write(stream)
    return stream.getvalue()


def main() -> None:
    templates = {v: template(v) for v in ('R2013', 'R2000')}
    lines = [
        '// Auto-generated by scripts/cad/build-dxf-templates.py (ezdxf ' + ezdxf.__version__ + ') — DO NOT EDIT',
        '//',
        '// Prázdné výkresy DXF (kostra pro AutoCAD): hlavička, tabulky, layouty,',
        '// slovníky; jvf-cad do nich doplňuje hladiny, typy čar, bloky a entity.',
        '',
        'export const DXF_TEMPLATES = {',
    ]
    for v, text in templates.items():
        lines.append(f'  {v}: {json.dumps(text)},')
    lines += ['} as const;', '']
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print(f'{OUT.relative_to(ROOT)}: ' + ', '.join(f'{v} {len(t.splitlines())} řádků' for v, t in templates.items()))


if __name__ == '__main__':
    main()
