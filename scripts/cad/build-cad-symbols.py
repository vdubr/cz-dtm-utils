#!/usr/bin/env python3
"""
Generátor geometrie symbolů pro export do CAD (balíček jvf-cad).

Profily:
  udm   knihovna symbolů ČKZ jvf_parser/docs/udm-2.1.1/knihovny/SVG (SVG v
        papírových px při 96 dpi, měřítko 1:500), symboly použité v
        jvf_parser/src/udm-2.1.1/generated/styles.ts
        → jvf_cad/src/generated/symbols.ts (UDM_CAD_SYMBOLS)
  zxml  značky SŽ vektorizované z fotokatalogu MOZeK
        jvf_parser/docs/zxml-1.5.1.6/knihovny/SVG (viewBox v px zdroje,
        width/height v jednotkách 0,01 mm papíru), symboly použité v
        jvf_parser/src/zxml-1.5.1.6/generated/styles.ts
        → jvf_cad/src/generated/symbols-zxml.ts (ZXML_CAD_SYMBOLS)

Výstup: kód symbolu → primitiva v METRECH, vkládací bod = střed symbolu
(u zxml střed viewBoxu), osa Y nahoru:
  ['p', closed, fill, [x, y, bulge, …]]   polylinie (oblouky jako bulge)
  ['c', x, y, r, fill]                    kružnice
  ['e', x, y, rx, ry, rotDeg]             elipsa (rx podél natočené osy X)
  ['t', x, y, výška, rotDeg, text, italic] text, zarovnaný na střed

Podporované SVG: polyline/polygon/line/circle/ellipse/path (M/L/A/Z)/text bez
vnořených transformací (kromě rotate u elipsy a translate/rotate u textu).
Výplň jen černá (#000000) ze `style` nebo atributu `fill` (i zděděného ze
skupiny <g>); tahy (fill none) → nevyplněná primitiva. Šířka tahu se do CAD
nepřenáší. Díry ve vyplněných cestách (fill-rule evenodd) se exportují jako
samostatné vyplněné polylinie — typ CadSymbolPrimitive díry nevyjadřuje.

Spuštění z rootu repa:
    python3 scripts/cad/build-cad-symbols.py --profile udm|zxml
"""
import argparse
import json
import math
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NS = '{http://www.w3.org/2000/svg}'
# Výška písmen (DXF TEXT = výška verzálek) ≈ 0,7 × velikost fontu.
CAP_HEIGHT = 0.7
# 1 mm papíru = 0,5 m při 1:500.
M_PER_MM = 0.5

PROFILES = {
    'udm': {
        'svg_dir': ROOT / 'jvf_parser/docs/udm-2.1.1/knihovny/SVG',
        'styles': ROOT / 'jvf_parser/src/udm-2.1.1/generated/styles.ts',
        'out': ROOT / 'jvf_cad/src/generated/symbols.ts',
        'prefix': 'Knihovna symbolu_UDM 2_',
        # 1 px (96 dpi) = 25,4/96 mm papíru
        'unit_mm': 25.4 / 96,
        'export': 'UDM_CAD_SYMBOLS',
        'header': [
            '// Auto-generated by scripts/udm/build-udm-cad-symbols.py — DO NOT EDIT',
            '//',
            '// Geometrie symbolů UDM (knihovna ČKZ) pro bloky v CAD: metry, střed =',
            '// vkládací bod, osa Y nahoru. Viz typ CadSymbolPrimitive v ../symbols.ts.',
        ],
    },
    'zxml': {
        'svg_dir': ROOT / 'jvf_parser/docs/zxml-1.5.1.6/knihovny/SVG',
        'styles': ROOT / 'jvf_parser/src/zxml-1.5.1.6/generated/styles.ts',
        'out': ROOT / 'jvf_cad/src/generated/symbols-zxml.ts',
        'prefix': '',
        # width/height v jednotkách 0,01 mm papíru (viewBox v px zdroje)
        'unit_mm': 0.01,
        'export': 'ZXML_CAD_SYMBOLS',
        'header': [
            '// Auto-generated by scripts/cad/build-cad-symbols.py --profile zxml — DO NOT EDIT',
            '//',
            '// Geometrie značek SŽ (fotokatalog MOZeK, vektorizace scripts/zxml/vectorize.py)',
            '// pro bloky v CAD: metry, střed = vkládací bod, osa Y nahoru. Viz typ',
            '// CadSymbolPrimitive v ../symbols.ts.',
        ],
    },
}


def r4(v: float) -> float:
    return round(v, 4)


def style_of(el) -> dict[str, str]:
    st = {}
    for part in (el.get('style') or '').split(';'):
        if ':' in part:
            k, v = part.split(':', 1)
            st[k.strip()] = v.strip()
    return st


def fill_of(el, parents) -> str:
    """Výplň elementu: style > atribut > zděděná ze skupiny (výchozí none)."""
    st = style_of(el)
    if 'fill' in st:
        return st['fill']
    if el.get('fill') is not None:
        return el.get('fill')
    for p in reversed(parents.get(el, [])):
        st = style_of(p)
        if 'fill' in st:
            return st['fill']
        if p.get('fill') is not None:
            return p.get('fill')
    return 'none'


def invisible(el) -> bool:
    return style_of(el).get('stroke-opacity') == '0'


def parse_points(s: str) -> list[tuple[float, float]]:
    nums = [float(n) for n in re.findall(r'-?[\d.]+(?:e-?\d+)?', s)]
    return list(zip(nums[0::2], nums[1::2]))


def arc_bulge(p1, p2, rx, ry, large, sweep) -> float:
    """SVG oblouk (kruhový) → DXF bulge v souřadnicích s osou Y nahoru."""
    r = (rx + ry) / 2
    d = math.dist(p1, p2)
    if d == 0:
        return 0.0
    r = max(r, d / 2)
    theta = 2 * math.asin(min(1.0, d / (2 * r)))
    if large:
        theta = 2 * math.pi - theta
    # sweep=1 = kladný úhel v SVG (osa Y dolů) → po převrácení Y proti směru
    # hodinových ručiček → kladný bulge.
    return math.tan(theta / 4) * (1 if sweep else -1)


def parse_path(d: str):
    """Absolutní M/L/A/Z → seznam (vrcholy [(x, y, bulge)], closed)."""
    tokens = re.findall(r'[MLAZmlaz]|-?[\d.]+(?:e-?\d+)?', d)
    subpaths, cur, closed, i, cmd = [], [], False, 0, None
    while i < len(tokens):
        t = tokens[i]
        if t.isalpha():
            cmd = t.upper()
            i += 1
            if cmd == 'Z':
                closed = True
                subpaths.append((cur, closed))
                cur, closed = [], False
            continue
        if cmd == 'M':
            if cur:
                subpaths.append((cur, closed))
            cur, closed = [[float(tokens[i]), float(tokens[i + 1]), 0.0]], False
            i += 2
            cmd = 'L'
        elif cmd == 'L':
            cur.append([float(tokens[i]), float(tokens[i + 1]), 0.0])
            i += 2
        elif cmd == 'A':
            rx, ry, _rot, large, sweep, x, y = (float(v) for v in tokens[i:i + 7])
            p1 = (cur[-1][0], cur[-1][1])
            cur[-1][2] = arc_bulge(p1, (x, y), rx, ry, int(large), int(sweep))
            cur.append([x, y, 0.0])
            i += 7
        else:
            i += 1
    if cur:
        subpaths.append((cur, closed))
    return subpaths


def frame(root, unit_mm: float) -> tuple[float, float, float, float, float]:
    """(x0, y0, šířka, výška rámce v jednotkách souřadnic, metry na jednotku)."""
    w, h = float(root.get('width')), float(root.get('height'))
    vb = root.get('viewBox')
    if vb:
        x0, y0, vw, vh = (float(v) for v in vb.replace(',', ' ').split())
        return x0, y0, vw, vh, (w / vw) * unit_mm * M_PER_MM
    return 0.0, 0.0, w, h, unit_mm * M_PER_MM


def convert(svg_path: Path, unit_mm: float) -> list:
    root = ET.parse(svg_path).getroot()
    x0, y0, w, h, k = frame(root, unit_mm)
    parents: dict = {}
    stack = [(root, [])]
    while stack:
        el, anc = stack.pop()
        parents[el] = anc
        for ch in el:
            stack.append((ch, anc + [el]))

    def X(x: float) -> float:
        return r4((x - x0 - w / 2) * k)

    def Y(y: float) -> float:
        return r4((y0 + h / 2 - y) * k)

    def is_fill(el) -> bool:
        return fill_of(el, parents).lower() == '#000000'

    prims = []
    for el in root.iter():
        tag = el.tag.replace(NS, '')
        if tag in ('polygon', 'polyline') and not invisible(el):
            pts = parse_points(el.get('points', ''))
            flat = [v for x, y in pts for v in (X(x), Y(y), 0)]
            prims.append(['p', 1 if tag == 'polygon' else 0, 1 if is_fill(el) else 0, flat])
        elif tag == 'line':
            x1, y1, x2, y2 = (float(el.get(a)) for a in ('x1', 'y1', 'x2', 'y2'))
            prims.append(['p', 0, 0, [X(x1), Y(y1), 0, X(x2), Y(y2), 0]])
        elif tag == 'circle':
            prims.append(['c', X(float(el.get('cx'))), Y(float(el.get('cy'))),
                          r4(float(el.get('r')) * k), 1 if is_fill(el) else 0])
        elif tag == 'ellipse':
            rot = 0.0
            m = re.search(r'rotate\(\s*(-?[\d.]+)', el.get('transform', ''))
            if m:
                rot = -float(m.group(1))
            prims.append(['e', X(float(el.get('cx'))), Y(float(el.get('cy'))),
                          r4(float(el.get('rx')) * k), r4(float(el.get('ry')) * k), r4(rot)])
        elif tag == 'path':
            for verts, closed in parse_path(el.get('d', '')):
                flat = [v for x, y, b in verts for v in (X(x), Y(y), r4(b))]
                prims.append(['p', 1 if closed else 0, 1 if is_fill(el) else 0, flat])
        elif tag == 'text':
            x, y = float(el.get('x', 0)), float(el.get('y', 0))
            tr = el.get('transform', '')
            ang = 0.0
            m = re.search(r'rotate\(\s*(-?[\d.]+)', tr)
            if m:
                ang = float(m.group(1))
                a = math.radians(ang)
                x, y = x * math.cos(a) - y * math.sin(a), x * math.sin(a) + y * math.cos(a)
            m = re.search(r'translate\(\s*(-?[\d.]+)[ ,]+(-?[\d.]+)', tr)
            if m:
                x, y = x + float(m.group(1)), y + float(m.group(2))
            size = float(el.get('font-size', '10'))
            prims.append(['t', X(x), Y(y), r4(size * k * CAP_HEIGHT), r4(-ang), ''.join(el.itertext()),
                          1 if el.get('font-style') == 'italic' else 0])
    return prims


def build(profile: str) -> None:
    cfg = PROFILES[profile]
    used = sorted(set(re.findall(r'"symbol":"([^"]+)"', cfg['styles'].read_text(encoding='utf-8'))))
    symbols, missing = {}, []
    for code in used:
        f = cfg['svg_dir'] / f'{cfg["prefix"]}{code}.svg'
        if not f.exists():
            missing.append(code)
            continue
        symbols[code] = convert(f, cfg['unit_mm'])
    lines = cfg['header'] + [
        '',
        "import type { CadSymbolPrimitive } from '../symbols.js';",
        '',
        f'export const {cfg["export"]}: Record<string, CadSymbolPrimitive[]> = {{',
    ]
    for code, prims in symbols.items():
        lines.append(f'  {json.dumps(code)}: {json.dumps(prims, ensure_ascii=False, separators=(",", ":"))},')
    lines += ['};', '']
    out = cfg['out']
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(lines), encoding='utf-8')
    print(f'{len(symbols)} symbolů → {out.relative_to(ROOT)} ({out.stat().st_size // 1024} kB), chybí: {missing}')


def main() -> None:
    ap = argparse.ArgumentParser(description='Geometrie symbolů pro export do CAD')
    ap.add_argument('--profile', choices=sorted(PROFILES), required=True)
    build(ap.parse_args().profile)


if __name__ == '__main__':
    main()
